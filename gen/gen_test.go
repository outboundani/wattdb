func repoRoot() string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..")
}

// copyModule copies testdata/taskapp to a temp dir, pointing its wattdb
// replace directive at this repository.
func copyModule(t *testing.T) string {
	t.Helper()
	src := filepath.Join(repoRoot(), "gen", "testdata", "taskapp")
	dst := t.TempDir()
	err := filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, path)
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if rel == "go.mod" {
			b = bytes.Replace(b, []byte("=> ../../.."), []byte("=> "+repoRoot()), 1)
		}
		return os.WriteFile(target, b, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
	return dst
}

func goCmd(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "WATTDB_VECTORS="+filepath.Join(repoRoot(), "testdata", "vectors"))
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return string(out)
}

// TestGenerateExample regenerates the example module and checks that the
// output matches the committed code, that it builds and vets, and that its
// tests (generated code against the ElectroDB vectors) pass.
func TestGenerateExample(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	mod := copyModule(t)
	committed := filepath.Join(repoRoot(), "gen", "testdata", "taskapp", "db")

	// Generate over an empty db directory, keeping hand-written test files.
	db := filepath.Join(mod, "db")
	generated, err := listGenerated(db)
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range generated {
		os.Remove(filepath.Join(db, f))
	}
	goCmd(t, repoRoot(), "run", "./cmd/wattdb", "generate", filepath.Join(mod, "schema"))

	got, err := listGenerated(db)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(got, ",") != strings.Join(generated, ",") {
		t.Fatalf("generated files %v, committed %v", got, generated)
	}
	for _, f := range got {
		a, _ := os.ReadFile(filepath.Join(db, f))
		b, _ := os.ReadFile(filepath.Join(committed, f))
		if !bytes.Equal(a, b) {
			t.Errorf("%s differs from the committed file; run go run ./cmd/wattdb generate gen/testdata/taskapp/schema", f)
		}
	}

	goCmd(t, mod, "vet", "./...")
	goCmd(t, mod, "test", "./...")
	if out := goCmd(t, repoRoot(), "run", "./cmd/wattdb", "check", filepath.Join(mod, "schema")); !strings.Contains(out, "valid") {
		t.Errorf("check output: %s", out)
	}
}

func listGenerated(dir string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return err
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(b, []byte("// Code generated by wattdb.")) {
			rel, _ := filepath.Rel(dir, path)
			out = append(out, rel)
		}
		return nil
	})
	return out, err
}

func TestNames(t *testing.T) {
	for _, tt := range []struct{ entity, version, want string }{
		{"user", "1", "user"},
		{"User", "2", "userv2"},
		{"taskComments", "1", "taskcomments"},
		{"team_members", "1", "teammembers"},
		{"type", "1", "typeentity"},
		{"9lives", "1", "e9lives"},
	} {
		if got := packageName(tt.entity, tt.version); got != tt.want {
			t.Errorf("packageName(%q, %q) = %q, want %q", tt.entity, tt.version, got, tt.want)
		}
	}
	if got := enumConst("RoleEnum", "in-progress"); got != "RoleInProgress" {
		t.Errorf("enumConst = %q", got)
	}
	if got := exportName("team_members"); got != "TeamMembers" {
		t.Errorf("exportName = %q", got)
	}
}

type fakeSchema struct {
	entity     string
	collection string
	index      string
}

func (f fakeSchema) Model() wattdb.Model {
	return wattdb.Model{Entity: f.entity, Version: "1", Service: testService}
}

func (f fakeSchema) Attributes() []wattdb.Attribute {
	return []wattdb.Attribute{attr.String("ID").Field("id")}
}

func (f fakeSchema) Indexes() []wattdb.Index {
	return []wattdb.Index{
		index.Primary("p").PKField("pk").PK("ID").SKField("sk").SK(),
		index.GSI("c", f.index).Collection(f.collection).PKField("gsi1pk").PK("ID").SKField("gsi1sk").SK(),
	}
}

var testService = wattdb.Service("svc")

func TestCheckCollections(t *testing.T) {
	ok := []Schema{{Value: fakeSchema{"a", "col", "gsi1"}}, {Value: fakeSchema{"b", "col", "gsi1"}}}
	if errs := checkCollections(ok); len(errs) != 0 {
		t.Errorf("unexpected errors: %v", errs)
	}
	bad := []Schema{{Value: fakeSchema{"a", "col", "gsi1"}}, {Value: fakeSchema{"b", "col", "gsi2"}}}
	if errs := checkCollections(bad); len(errs) != 1 {
		t.Errorf("want one collection error, got %v", errs)
	}
}
